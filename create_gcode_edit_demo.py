"""Create an offline two-layer inspection fixture and temperature-edited copy.

The file is a G-code viewer fixture, not a prepared printer job. No networking.
"""
from copy import deepcopy
import difflib
import json
from pathlib import Path
from flow_scheduler import schedule_text

DEMO_CONFIG = {
    'output_mode': 'temperature_test', 'tool_binding_confirmed': True,
    'physical_tool': 2, 'logical_tool': 2, 'filament_type': 'PLA', 'nozzle_diameter_mm': 0.8,
    'min_temperature_c': 210,
    'max_temperature_c': 245, 'max_flow_mm3_s': 75, 'headroom_percent': 10,
    'interpolation': 'linear', 'heating_lead_s': 6.3, 'cooling_hold_s': 10.3,
    'points': [{'temperature_c': t, 'max_reliable_flow_mm3_s': q}
               for t, q in ((210, 30), (220, 38), (230, 50), (245, 75))],
    'motion': {'max_velocity_mm_s': 750, 'max_accel_mm_s2': 10000,
               'square_corner_velocity_mm_s': 15, 'minimum_cruise_ratio': 0.5},
}


def demo_gcode():
    lines = ['; Orca Flow offline G-code viewer fixture - not a prepared printer job',
             '; generated by OrcaSlicer-style test fixture',
             'G90', 'M83', 'T2', 'G1 X80 Y80 Z0.2 F6000', 'M104 T2 S230',
             ';LAYER_CHANGE', ';Z:0.2', ';TYPE:Outer wall', 'G1 X180 E4 F6000',
             ';LAYER_CHANGE', ';Z:0.4', 'G1 Z0.4 F600',
             ';TYPE:Internal infill', 'M204 S10000']
    i = 0
    for count, e in ((10, 4), (16, 20), (26, 4)):
        for _ in range(count):
            lines.append(f'G1 X{80 if i % 2 == 0 else 180} Y{81+i} E{e} F6000')
            i += 1
    lines.extend([';TYPE:Custom', 'M104 T2 S0', 'M140 S0', '; EXECUTABLE_BLOCK_END',
                  '; CONFIG_BLOCK_START', '; filament_type = PLA;PLA;PLA;PLA',
                  '; nozzle_diameter = 0.4,0.4,0.8,0.8', '; filament_diameter = 1.75,1.75,1.75,1.75',
                  '; filament_map = 1,2,3,4', '; CONFIG_BLOCK_END'])
    return '\n'.join(lines)+'\n'


def main():
    directory = Path(__file__).parent/'.build'/'gcode-edit-demo'
    directory.mkdir(parents=True,exist_ok=True)
    source = demo_gcode()
    edited, report = schedule_text(source, deepcopy(DEMO_CONFIG))
    (directory/'source.gcode').write_text(source, encoding='utf-8')
    (directory/'temperature-test.gcode').write_text(edited, encoding='utf-8')
    (directory/'report.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    (directory/'config.json').write_text(json.dumps(DEMO_CONFIG, indent=2), encoding='utf-8')
    diff = ''.join(difflib.unified_diff(source.splitlines(keepends=True), edited.splitlines(keepends=True),
                                     fromfile='source.gcode', tofile='temperature-test.gcode'))
    (directory/'temperature-changes.diff').write_text(diff, encoding='utf-8')
    print(json.dumps({k: v for k, v in report.items() if k != 'events'}, indent=2))
    print(diff)


if __name__ == '__main__':
    main()
